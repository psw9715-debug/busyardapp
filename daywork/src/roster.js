// 차량번호 명부
//
// 모든 번호는 4자리이고 첫 자리는 1이다 (차고지 앱과 같은 규칙).
// 아래 구간은 2026-10-02 에 운영자가 불러 준 것으로, 그동안 일지에 실제로
// 적힌 87종이 하나도 빠짐없이 이 안에 들어간다. 구간이 실제 보유 대수보다
// 조금 넓은데, 그 방향이 안전하다 — 넓으면 "있을 수 없는 번호" 몇 개를 못
// 걸러낼 뿐이지만, 좁으면 멀쩡한 차를 못 적는다.
//
// 브라우저 API를 쓰지 않는 순수 로직이라 테스트 페이지에서 그대로 검사한다.

const RANGES = [
  [1012, 1031],
  [1113, 1170],   // 1113~1132 + 1133~1170 (붙어 있어 한 구간으로)
  [1201, 1209],
  [1301, 1305],
  [1333, 1355],
  [1501, 1512],
  [1701, 1754],
];

const SET = new Set();
for (const [from, to] of RANGES) {
  for (let n = from; n <= to; n++) SET.add(String(n));
}

export const size = SET.size;

/** 명부에 있는 번호인가. 없어도 입력을 막지는 않는다 — 노란 카드로 세워 둔다. */
export function isKnown(plate) {
  return SET.has(String(plate));
}

/** 명부 전체 (진단 화면에서 보여 주려고) */
export function all() {
  return [...SET].sort();
}
